-- ---------------------------------------------------------------------------
-- apply_approval: the only path that turns a proposal into a data change.
-- On kapasitas_tidak_cukup the whole transaction rolls back and the approval
-- stays pending. The application then records the reason (section 8.5).
-- ---------------------------------------------------------------------------
create or replace function apply_approval(
  p_approval_id uuid, p_decider uuid, p_setuju boolean, p_catatan text
) returns text
language plpgsql
set search_path = public, pg_temp
as $$
declare
  a approvals%rowtype;
  asg project_assignments%rowtype;
  v vendors%rowtype;
  v_id uuid;
  v_data jsonb;
  v_paralel int;
  v_tenaga int;
begin
  if not exists (select 1 from profiles where id = p_decider and role = 'kepala_dinas') then
    raise exception 'bukan_pemutus';
  end if;

  select * into a from approvals where id = p_approval_id for update;
  if not found or a.status <> 'pending' then
    return 'sudah_diputuskan';
  end if;

  if not p_setuju then
    update approvals set status = 'rejected', diputuskan_oleh = p_decider,
           catatan = p_catatan, decided_at = now() where id = a.id;
    if a.jenis = 'project_assignment' then
      update project_assignments set status = 'dibatalkan'
       where id = (a.payload->>'assignment_id')::uuid and status = 'diusulkan';
    elsif a.jenis = 'vendor_activation' then
      update vendors set status = 'ditolak', updated_at = now()
       where id = (a.payload->>'vendor_id')::uuid and status = 'verifikasi';
    end if;
    insert into audit_logs (actor_id, aksi, target, detail)
      values (p_decider, 'approval_ditolak', a.id::text, a.payload);
    return 'ditolak';
  end if;

  if a.jenis = 'project_assignment' then
    select * into asg from project_assignments
     where id = (a.payload->>'assignment_id')::uuid for update;
    if not found or asg.status <> 'diusulkan' then
      raise exception 'penugasan_tidak_valid';
    end if;

    -- Lock the vendor so two approvals cannot both take the last slot.
    select * into v from vendors where id = asg.vendor_id for update;

    select count(*)::int, coalesce(sum(tenaga_dialokasikan), 0)::int
      into v_paralel, v_tenaga
      from project_assignments
     where vendor_id = v.id and id <> asg.id
       and status in ('disetujui', 'berjalan')
       and daterange(mulai, selesai, '[]') && daterange(asg.mulai, asg.selesai, '[]');

    if v_paralel >= v.kapasitas_proyek
       or v.total_tenaga - v_tenaga < asg.tenaga_dialokasikan then
      raise exception 'kapasitas_tidak_cukup';
    end if;

    update project_assignments set status = 'disetujui', approval_id = a.id
     where id = asg.id;
  elsif a.jenis = 'vendor_activation' then
    update vendors set status = 'aktif', updated_at = now()
     where id = (a.payload->>'vendor_id')::uuid and status = 'verifikasi';
    if not found then
      raise exception 'vendor_tidak_valid';
    end if;
  elsif a.jenis = 'vendor_update' then
    v_id := (a.payload->>'vendor_id')::uuid;
    v_data := a.payload->'data';
    select * into v from vendors where id = v_id for update;
    if not found or v.status <> 'aktif' or jsonb_typeof(v_data) is distinct from 'object' then
      raise exception 'vendor_tidak_valid';
    end if;
    if jsonb_typeof(v_data->'layanan') is distinct from 'array' then
      raise exception 'data_tidak_valid';
    end if;
    if exists (
      select 1
        from jsonb_to_recordset(v_data->'layanan') as x(category_id int)
        left join service_categories c on c.id = x.category_id
       where x.category_id is null or c.id is null
    ) then
      raise exception 'kategori_tidak_valid';
    end if;

    if exists (
      with events as (
        select a1.mulai as tanggal, 1::int as proyek_delta, a1.tenaga_dialokasikan as tenaga_delta
          from project_assignments a1
         where a1.vendor_id = v.id and a1.status in ('disetujui', 'berjalan')
        union all
        select a1.selesai + 1, -1::int, -a1.tenaga_dialokasikan
          from project_assignments a1
         where a1.vendor_id = v.id and a1.status in ('disetujui', 'berjalan')
      ),
      harian as (
        select tanggal, sum(proyek_delta) as proyek_delta, sum(tenaga_delta) as tenaga_delta
          from events
         group by tanggal
      ),
      beban as (
        select sum(proyek_delta) over (order by tanggal) as proyek,
               sum(tenaga_delta) over (order by tanggal) as tenaga
          from harian
      )
      select 1 from beban
       where proyek > (v_data->>'kapasitas_proyek')::int
          or tenaga > (v_data->>'total_tenaga')::int
    ) then
      raise exception 'kapasitas_tidak_cukup';
    end if;

    update vendors
       set nama = v_data->>'nama', npwp = v_data->>'npwp', alamat = v_data->>'alamat',
           wilayah = v_data->>'wilayah', kontak = v_data->>'kontak', tipe = v_data->>'tipe',
           kapasitas_proyek = (v_data->>'kapasitas_proyek')::int,
           total_tenaga = (v_data->>'total_tenaga')::int, updated_at = now()
     where id = v.id;
    delete from vendor_services where vendor_id = v.id;
    insert into vendor_services (vendor_id, category_id, nama_layanan, tipe, deskripsi, harga_min, harga_maks, satuan)
    select v.id, c.id, x.nama_layanan, c.tipe, x.deskripsi, x.harga_min, x.harga_maks, x.satuan
      from jsonb_to_recordset(v_data->'layanan') as x(
             category_id int, nama_layanan text, deskripsi text,
             harga_min numeric, harga_maks numeric, satuan text)
      join service_categories c on c.id = x.category_id;
  elsif a.jenis = 'vendor_archive' then
    v_id := (a.payload->>'vendor_id')::uuid;
    select * into v from vendors where id = v_id for update;
    if not found or v.status = 'diarsipkan' then
      raise exception 'vendor_tidak_valid';
    end if;
    if exists (
      select 1 from project_assignments
       where vendor_id = v.id and status in ('diusulkan', 'disetujui', 'berjalan')
    ) then
      raise exception 'vendor_memiliki_penugasan_aktif';
    end if;
    update vendors set status = 'diarsipkan', updated_at = now() where id = v.id;
  end if;

  update approvals set status = 'approved', diputuskan_oleh = p_decider,
         catatan = p_catatan, decided_at = now() where id = a.id;
  insert into audit_logs (actor_id, aksi, target, detail)
    values (p_decider, 'approval_disetujui', a.id::text, a.payload);
  return 'disetujui';
end $$;

-- ---------------------------------------------------------------------------
-- ajukan_penugasan: creates one assignment proposal and one pending approval.
-- It does not reduce capacity. It is kept atomic so neither row may exist alone.
-- ---------------------------------------------------------------------------
create or replace function ajukan_penugasan(
  p_actor uuid,
  p_project_id uuid,
  p_vendor_id uuid,
  p_tenaga int,
  p_mulai date,
  p_selesai date,
  p_nilai numeric default null
) returns jsonb
language plpgsql
set search_path = public, pg_temp
as $$
declare
  actor profiles%rowtype;
  proyek projects%rowtype;
  vendor vendors%rowtype;
  assg project_assignments%rowtype;
  v_approval_id uuid;
begin
  select * into actor from profiles where id = p_actor;
  if not found or actor.role not in ('admin_pengadaan', 'pic_proyek') then
    raise exception 'bukan_pengusul';
  end if;

  select * into proyek from projects where id = p_project_id for update;
  if not found then
    raise exception 'proyek_tidak_valid';
  end if;
  if actor.role = 'pic_proyek' and proyek.opd_id is distinct from actor.opd_id then
    raise exception 'proyek_diluar_dinas';
  end if;
  if proyek.status not in ('rencana', 'mencari_vendor', 'ditunda') then
    raise exception 'proyek_tidak_menerima_vendor';
  end if;
  if p_selesai < p_mulai or p_mulai < proyek.mulai or p_selesai > proyek.selesai then
    raise exception 'periode_diluar_proyek';
  end if;
  if p_tenaga < 0 or (p_nilai is not null and p_nilai < 0) then
    raise exception 'nilai_tidak_valid';
  end if;

  select * into vendor from vendors where id = p_vendor_id for update;
  if not found or vendor.status <> 'aktif' then
    raise exception 'vendor_tidak_aktif';
  end if;
  if exists (
    select 1 from approvals
     where jenis = 'vendor_archive' and status = 'pending'
       and payload->>'vendor_id' = p_vendor_id::text
  ) then
    raise exception 'vendor_dalam_proses_arsip';
  end if;
  if exists (
    select 1 from project_assignments
    where project_id = p_project_id
      and vendor_id = p_vendor_id
      and status in ('diusulkan', 'disetujui', 'berjalan')
  ) then
    raise exception 'penugasan_sudah_ada';
  end if;

  insert into project_assignments (
    project_id, vendor_id, status, tenaga_dialokasikan,
    mulai, selesai, nilai
  ) values (
    p_project_id, p_vendor_id, 'diusulkan', p_tenaga,
    p_mulai, p_selesai, p_nilai
  ) returning * into assg;

  insert into approvals (
    jenis, payload, status, diusulkan_oleh
  ) values (
    'project_assignment',
    jsonb_build_object(
      'assignment_id', assg.id,
      'project_id', p_project_id,
      'vendor_id', p_vendor_id
    ),
    'pending',
    p_actor
  ) returning id into v_approval_id;

  update project_assignments set approval_id = v_approval_id
  where id = assg.id;

  insert into audit_logs (actor_id, aksi, target, detail)
  values (
    p_actor,
    'penugasan_diusulkan',
    assg.id::text,
    jsonb_build_object(
      'approval_id', v_approval_id,
      'project_id', p_project_id,
      'vendor_id', p_vendor_id,
      'tenaga', p_tenaga,
      'mulai', p_mulai,
      'selesai', p_selesai,
      'nilai', p_nilai
    )
  );

  return jsonb_build_object(
    'assignment_id', assg.id,
    'approval_id', v_approval_id,
    'status', 'diusulkan'
  );
end $$;

-- ---------------------------------------------------------------------------
-- cari_vendor: typo-tolerant vendor search. A null status excludes archived records.
-- ---------------------------------------------------------------------------
create or replace function cari_vendor(
  p_kata_kunci text default null,
  p_kategori text default null,
  p_tipe text default null,
  p_wilayah text default null,
  p_status text default 'aktif',
  p_limit int default 20
)
returns table (
  id uuid, nama text, npwp text, wilayah text, tipe text, status text,
  kapasitas_proyek int, total_tenaga int,
  kategori text[], layanan text[], harga_min numeric, harga_maks numeric,
  sertifikat_berlaku text[], rating numeric, jumlah_penilaian int, relevansi numeric
)
language sql stable
set search_path = public, extensions, pg_temp
as $$
with q as (
  select nullif(trim(p_kata_kunci), '') as kata,
         nullif(trim(p_kategori), '') as kat,
         nullif(trim(p_wilayah), '') as wil
),
skor as (
  select v.id,
         case when q.kata is null then 1::real else greatest(
           word_similarity(q.kata, v.nama),
           coalesce((select max(greatest(
                       word_similarity(q.kata, s.nama_layanan),
                       word_similarity(q.kata, coalesce(s.deskripsi, '')),
                       word_similarity(q.kata, c.nama)))
                       from vendor_services s
                       join service_categories c on c.id = s.category_id
                      where s.vendor_id = v.id), 0)
         ) end as r
    from vendors v, q
   where ((p_status is null and v.status <> 'diarsipkan') or v.status = p_status)
     and (p_tipe is null or v.tipe = p_tipe or v.tipe = 'barang_jasa')
     and (q.wil is null or word_similarity(q.wil, coalesce(v.wilayah, '')) >= 0.75)
     and (q.kat is null or exists (
           select 1 from vendor_services s
             join service_categories c on c.id = s.category_id
            where s.vendor_id = v.id and word_similarity(q.kat, c.nama) >= 0.75))
)
select v.id, v.nama, v.npwp, v.wilayah, v.tipe, v.status,
       v.kapasitas_proyek, v.total_tenaga,
       coalesce((select array_agg(distinct c.nama order by c.nama) from vendor_services s
                  join service_categories c on c.id = s.category_id where s.vendor_id = v.id), '{}'),
       coalesce((select array_agg(s.nama_layanan order by s.nama_layanan)
                   from vendor_services s where s.vendor_id = v.id), '{}'),
       (select min(s.harga_min) from vendor_services s where s.vendor_id = v.id),
       (select max(s.harga_maks) from vendor_services s where s.vendor_id = v.id),
       coalesce((select array_agg(distinct c.jenis order by c.jenis) from vendor_certifications c
                  where c.vendor_id = v.id and c.berlaku_sampai >= current_date), '{}'),
       (select round(avg(r.skor_kualitas), 2) from vendor_ratings r where r.vendor_id = v.id),
       (select count(*)::int from vendor_ratings r where r.vendor_id = v.id),
       round(skor.r::numeric, 3)
  from skor
  join vendors v on v.id = skor.id
 where skor.r >= 0.6
 order by skor.r desc, v.nama asc
 limit least(greatest(coalesce(p_limit, 20), 1), 100);
$$;

-- ---------------------------------------------------------------------------
-- detail_vendor: full vendor profile. Dates and warnings are computed here.
-- ---------------------------------------------------------------------------
create or replace function detail_vendor(p_vendor_id uuid)
returns jsonb
language sql stable
set search_path = public, pg_temp
as $$
with sertifikat as (
  select c.jenis, c.nomor, c.berlaku_sampai,
         (c.berlaku_sampai - current_date) as sisa_hari,
         case when c.berlaku_sampai < current_date then 'kedaluwarsa'
              when c.berlaku_sampai <= current_date + 60 then 'hampir_habis'
              else 'berlaku' end as status_berlaku
    from vendor_certifications c
   where c.vendor_id = p_vendor_id
),
beban as (
  select count(*)::int as proyek, coalesce(sum(a.tenaga_dialokasikan), 0)::int as tenaga
    from project_assignments a
   where a.vendor_id = p_vendor_id
     and a.status in ('disetujui', 'berjalan')
     and current_date between a.mulai and a.selesai
),
nilai as (
  select round(avg(r.skor_kualitas), 2) as rata_rata, count(*)::int as jumlah,
         round(100.0 * avg(case when r.tepat_waktu then 1 else 0 end), 0) as tepat_waktu_persen
    from vendor_ratings r
   where r.vendor_id = p_vendor_id
)
select jsonb_build_object(
  'id', v.id, 'nama', v.nama, 'npwp', v.npwp, 'alamat', v.alamat, 'wilayah', v.wilayah,
  'kontak', v.kontak, 'tipe', v.tipe, 'status', v.status,
  'kapasitas_proyek', v.kapasitas_proyek, 'total_tenaga', v.total_tenaga,
  'diperbarui', v.updated_at::date,
  'beban', jsonb_build_object(
    'proyek_berjalan', b.proyek, 'tenaga_terpakai', b.tenaga,
    'sisa_proyek', greatest(v.kapasitas_proyek - b.proyek, 0),
    'sisa_tenaga', greatest(v.total_tenaga - b.tenaga, 0)),
  'penilaian', jsonb_build_object(
    'rata_rata', n.rata_rata, 'jumlah', n.jumlah, 'tepat_waktu_persen', n.tepat_waktu_persen),
  'layanan', coalesce((
    select jsonb_agg(jsonb_build_object(
             'id', s.id, 'category_id', s.category_id, 'kategori', c.nama, 'nama_layanan', s.nama_layanan,
             'tipe', s.tipe, 'deskripsi', s.deskripsi, 'harga_min', s.harga_min,
             'harga_maks', s.harga_maks, 'satuan', s.satuan) order by c.nama, s.nama_layanan)
      from vendor_services s join service_categories c on c.id = s.category_id
     where s.vendor_id = v.id), '[]'::jsonb),
  'sertifikat', coalesce((
    select jsonb_agg(to_jsonb(x) order by x.berlaku_sampai) from sertifikat x), '[]'::jsonb),
  'tidak_tersedia', coalesce((
    select jsonb_agg(jsonb_build_object('mulai', u.mulai, 'selesai', u.selesai, 'alasan', u.alasan) order by u.mulai)
      from vendor_unavailability u
     where u.vendor_id = v.id and u.selesai >= current_date), '[]'::jsonb),
  'dokumen', coalesce((
    select jsonb_agg(jsonb_build_object('jenis', d.jenis, 'status_cek', d.status_cek) order by d.jenis)
      from vendor_documents d where d.vendor_id = v.id), '[]'::jsonb),
  'riwayat', coalesce((
    select jsonb_agg(h.item order by h.mulai desc) from (
      select a.mulai, jsonb_build_object('nomor', p.nomor, 'judul', p.judul, 'status', a.status,
                                         'mulai', a.mulai, 'selesai', a.selesai) as item
        from project_assignments a join projects p on p.id = a.project_id
       where a.vendor_id = v.id and a.status <> 'dibatalkan'
       order by a.mulai desc limit 10) h), '[]'::jsonb),
  'peringatan', to_jsonb(array_remove(array[
      case when v.status = 'daftar_hitam' then 'Vendor berstatus daftar hitam.' end,
      case when exists (select 1 from sertifikat x where x.status_berlaku = 'kedaluwarsa')
           then 'Sertifikat kedaluwarsa: ' || (select string_agg(x.jenis, ', ' order by x.jenis) from sertifikat x where x.status_berlaku = 'kedaluwarsa') || '.' end,
      case when exists (select 1 from sertifikat x where x.status_berlaku = 'hampir_habis')
           then 'Sertifikat hampir habis: ' || (select string_agg(x.jenis, ', ' order by x.jenis) from sertifikat x where x.status_berlaku = 'hampir_habis') || '.' end
    ], null))
)
from vendors v, beban b, nilai n
where v.id = p_vendor_id;
$$;

-- ---------------------------------------------------------------------------
-- simpan_draft_vendor: saves registration data as a draft in one transaction.
-- It can never activate a vendor. Activation goes through apply_approval().
-- ---------------------------------------------------------------------------
create or replace function simpan_draft_vendor(p_actor uuid, p_vendor_id uuid, p_data jsonb)
returns uuid
language plpgsql
set search_path = public, pg_temp
as $$
declare
  actor profiles%rowtype;
  target uuid := p_vendor_id;
  current_status text;
begin
  select * into actor from profiles where id = p_actor;
  if not found or actor.role not in ('admin_pengadaan', 'vendor') then
    raise exception 'akses_ditolak';
  end if;
  if actor.role = 'vendor' then
    if p_vendor_id is distinct from actor.vendor_id then
      raise exception 'akses_ditolak';
    end if;
  end if;

  if target is null then
    insert into vendors (nama, npwp, alamat, wilayah, kontak, tipe, status, kapasitas_proyek, total_tenaga)
    values (p_data->>'nama', p_data->>'npwp', p_data->>'alamat', p_data->>'wilayah',
            p_data->>'kontak', p_data->>'tipe', 'draft',
            coalesce((p_data->>'kapasitas_proyek')::int, 1),
            coalesce((p_data->>'total_tenaga')::int, 0))
    returning id into target;
    if actor.role = 'vendor' then
      update profiles set vendor_id = target where id = actor.id;
    end if;
  else
    select status into current_status from vendors where id = target for update;
    if not found then
      raise exception 'vendor_tidak_ditemukan';
    end if;
    -- A rejected vendor may fix its data and go back to draft (section 10.4).
    if current_status not in ('draft', 'ditolak') then
      raise exception 'bukan_draft';
    end if;
    update vendors
       set status = 'draft',
           nama = p_data->>'nama', npwp = p_data->>'npwp', alamat = p_data->>'alamat',
           wilayah = p_data->>'wilayah', kontak = p_data->>'kontak', tipe = p_data->>'tipe',
           kapasitas_proyek = coalesce((p_data->>'kapasitas_proyek')::int, kapasitas_proyek),
           total_tenaga = coalesce((p_data->>'total_tenaga')::int, total_tenaga),
           updated_at = now()
     where id = target;
    delete from vendor_services where vendor_id = target;
  end if;

  insert into vendor_services (vendor_id, category_id, nama_layanan, tipe, deskripsi, harga_min, harga_maks, satuan)
  select target, c.id, x.nama_layanan, c.tipe, x.deskripsi, x.harga_min, x.harga_maks, x.satuan
    from jsonb_to_recordset(p_data->'layanan') as x(
           category_id int, nama_layanan text, deskripsi text,
           harga_min numeric, harga_maks numeric, satuan text)
    join service_categories c on c.id = x.category_id;

  insert into audit_logs (actor_id, aksi, target, detail)
  values (p_actor, 'vendor_draft_disimpan', target::text,
          jsonb_build_object('nama', p_data->>'nama', 'jumlah_layanan', jsonb_array_length(p_data->'layanan')));
  return target;
end $$;

-- ajukan_perubahan_vendor: stores proposed edits without changing an active vendor.
create or replace function ajukan_perubahan_vendor(p_actor uuid, p_vendor_id uuid, p_data jsonb)
returns jsonb
language plpgsql
set search_path = public, pg_temp
as $$
declare
  actor profiles%rowtype;
  target vendors%rowtype;
  approval_id uuid;
begin
  select * into actor from profiles where id = p_actor;
  if not found or actor.role <> 'admin_pengadaan' then
    raise exception 'akses_ditolak';
  end if;

  select * into target from vendors where id = p_vendor_id for update;
  if not found or target.status <> 'aktif' then
    raise exception 'vendor_tidak_valid';
  end if;
  if jsonb_typeof(p_data) is distinct from 'object'
     or jsonb_typeof(p_data->'layanan') is distinct from 'array' then
    raise exception 'data_tidak_valid';
  end if;
  if exists (
    select 1
      from jsonb_to_recordset(p_data->'layanan') as x(category_id int)
      left join service_categories c on c.id = x.category_id
     where x.category_id is null or c.id is null
  ) then
    raise exception 'kategori_tidak_valid';
  end if;
  if exists (
    select 1 from vendors
     where npwp = p_data->>'npwp' and id <> target.id
  ) then
    raise exception 'npwp_terdaftar';
  end if;
  if exists (
    select 1 from approvals
     where jenis in ('vendor_update', 'vendor_archive') and status = 'pending'
       and payload->>'vendor_id' = target.id::text
  ) then
    raise exception 'vendor_sudah_memiliki_usulan';
  end if;

  insert into approvals (jenis, payload, status, diusulkan_oleh)
  values (
    'vendor_update',
    jsonb_build_object('vendor_id', target.id, 'data', p_data),
    'pending',
    p_actor
  ) returning id into approval_id;

  insert into audit_logs (actor_id, aksi, target, detail)
  values (p_actor, 'vendor_perubahan_diusulkan', target.id::text,
          jsonb_build_object('approval_id', approval_id, 'nama', p_data->>'nama'));

  return jsonb_build_object('approval_id', approval_id, 'status', 'pending');
end $$;

-- ajukan_arsip_vendor: asks for approval to hide a vendor without deleting history.
