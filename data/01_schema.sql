-- ---------------------------------------------------------------------------
-- daftar_proyek: projects visible to the actor. The role is read from profiles.
-- Vendor accounts see only their own assignment and never the project budget.
-- ---------------------------------------------------------------------------
create or replace function daftar_proyek(
  p_actor uuid,
  p_kata_kunci text default null,
  p_status text default null,
  p_dinas text default null,
  p_mulai date default null,
  p_selesai date default null,
  p_tanpa_vendor boolean default false,
  p_limit int default 20
)
returns table (
  id uuid, nomor text, judul text, opd_id int, opd text, status text,
  mulai date, selesai date, anggaran numeric, wilayah text, prioritas text,
  kategori text[], tenaga_min int, sertifikat_wajib text[],
  vendor text[], jumlah_usulan int, relevansi numeric
)
language sql stable
set search_path = public, extensions, pg_temp
as $$
with actor as (
  select pf.role, pf.opd_id, pf.vendor_id from profiles pf where pf.id = p_actor
),
q as (
  select nullif(trim(p_kata_kunci), '') as kata, nullif(trim(p_dinas), '') as dinas
),
visible as (
  select pr.*, o.nama as opd_nama, a.role as actor_role, a.vendor_id as actor_vendor,
         case when q.kata is null or lower(pr.nomor) = lower(q.kata) then 1::real
              else greatest(word_similarity(q.kata, pr.judul),
                            word_similarity(q.kata, coalesce(pr.deskripsi, ''))) end as r
    from projects pr
    join opd o on o.id = pr.opd_id
   cross join actor a
   cross join q
   where (a.role in ('admin_pengadaan', 'kepala_dinas')
          or (a.role = 'pic_proyek' and pr.opd_id = a.opd_id)
          or (a.role = 'vendor' and exists (
                select 1 from project_assignments x
                 where x.project_id = pr.id and x.vendor_id = a.vendor_id
                   and x.status in ('disetujui', 'berjalan', 'selesai'))))
     and (p_status is null or pr.status = p_status)
     and (q.dinas is null or lower(o.kode) = lower(q.dinas) or word_similarity(q.dinas, o.nama) >= 0.75)
     and (p_mulai is null or pr.selesai >= p_mulai)
     and (p_selesai is null or pr.mulai <= p_selesai)
     and (not coalesce(p_tanpa_vendor, false) or (
           pr.status in ('rencana', 'mencari_vendor', 'ditunda')
           and not exists (select 1 from project_assignments x
                            where x.project_id = pr.id
                              and x.status in ('disetujui', 'berjalan', 'selesai'))))
)
select v.id, v.nomor, v.judul, v.opd_id, v.opd_nama, v.status, v.mulai, v.selesai,
       case when v.actor_role = 'vendor' then null else v.anggaran end,
       v.wilayah, v.prioritas,
       coalesce((select array_agg(distinct c.nama order by c.nama) from project_requirements rq
                  join service_categories c on c.id = rq.category_id where rq.project_id = v.id), '{}'),
       coalesce((select max(rq.tenaga_min)::int from project_requirements rq where rq.project_id = v.id), 0),
       coalesce((select array_agg(distinct s order by s) from project_requirements rq
                  cross join lateral unnest(rq.sertifikat_wajib) as s where rq.project_id = v.id), '{}'),
       coalesce((select array_agg(distinct vn.nama order by vn.nama) from project_assignments x
                  join vendors vn on vn.id = x.vendor_id
                 where x.project_id = v.id and x.status in ('disetujui', 'berjalan', 'selesai')
                   and (v.actor_role <> 'vendor' or x.vendor_id = v.actor_vendor)), '{}'),
       case when v.actor_role = 'vendor' then 0
            else (select count(*)::int from project_assignments x
                   where x.project_id = v.id and x.status = 'diusulkan') end,
       round(v.r::numeric, 3)
  from visible v
 where v.r >= 0.6
 order by v.r desc, v.mulai desc, v.nomor asc
 limit least(greatest(coalesce(p_limit, 20), 1), 200);
$$;

-- ---------------------------------------------------------------------------
-- detail_proyek: one project with requirements and assignments, or null when
-- the actor may not see it.
-- ---------------------------------------------------------------------------
create or replace function detail_proyek(p_actor uuid, p_project_id uuid)
returns jsonb
language sql stable
set search_path = public, pg_temp
as $$
with actor as (
  select pf.role, pf.opd_id, pf.vendor_id from profiles pf where pf.id = p_actor
)
select jsonb_build_object(
  'id', pr.id, 'nomor', pr.nomor, 'judul', pr.judul, 'deskripsi', pr.deskripsi,
  'opd', o.nama, 'status', pr.status, 'mulai', pr.mulai, 'selesai', pr.selesai,
  'anggaran', case when a.role = 'vendor' then null else pr.anggaran end,
  'wilayah', pr.wilayah, 'prioritas', pr.prioritas,
  'kebutuhan', coalesce((
    select jsonb_agg(jsonb_build_object(
             'kategori', c.nama, 'tenaga_min', rq.tenaga_min,
             'sertifikat_wajib', to_jsonb(rq.sertifikat_wajib), 'catatan', rq.catatan) order by c.nama)
      from project_requirements rq join service_categories c on c.id = rq.category_id
     where rq.project_id = pr.id), '[]'::jsonb),
  'penugasan', coalesce((
    select jsonb_agg(jsonb_build_object(
             'id', x.id, 'vendor_id', x.vendor_id, 'vendor', vn.nama, 'status', x.status,
             'tenaga_dialokasikan', x.tenaga_dialokasikan, 'mulai', x.mulai, 'selesai', x.selesai,
             'nilai', x.nilai) order by x.mulai, vn.nama)
      from project_assignments x join vendors vn on vn.id = x.vendor_id
     where x.project_id = pr.id
       and (a.role <> 'vendor' or (x.vendor_id = a.vendor_id
            and x.status in ('disetujui', 'berjalan', 'selesai')))), '[]'::jsonb)
)
from projects pr
join opd o on o.id = pr.opd_id
cross join actor a
where pr.id = p_project_id
  and (a.role in ('admin_pengadaan', 'kepala_dinas')
       or (a.role = 'pic_proyek' and pr.opd_id = a.opd_id)
       or (a.role = 'vendor' and exists (
             select 1 from project_assignments x
              where x.project_id = pr.id and x.vendor_id = a.vendor_id
                and x.status in ('disetujui', 'berjalan', 'selesai'))));
$$;

-- ---------------------------------------------------------------------------
-- daftar_penugasan: assignments visible to the actor.
-- ---------------------------------------------------------------------------
create or replace function daftar_penugasan(
  p_actor uuid,
  p_kata_kunci text default null,
  p_status text default null,
  p_limit int default 200
)
returns table (
  id uuid, project_id uuid, nomor text, judul text, opd text,
  vendor_id uuid, vendor text, status text, tenaga_dialokasikan int,
  mulai date, selesai date, nilai numeric
)
language sql stable
set search_path = public, extensions, pg_temp
as $$
with actor as (
  select pf.role, pf.opd_id, pf.vendor_id from profiles pf where pf.id = p_actor
),
q as (
  select nullif(trim(p_kata_kunci), '') as kata
)
select x.id, pr.id, pr.nomor, pr.judul, o.nama, vn.id, vn.nama, x.status,
       x.tenaga_dialokasikan, x.mulai, x.selesai, x.nilai
  from project_assignments x
  join projects pr on pr.id = x.project_id
  join opd o on o.id = pr.opd_id
  join vendors vn on vn.id = x.vendor_id
 cross join actor a
 cross join q
 where (a.role in ('admin_pengadaan', 'kepala_dinas')
        or (a.role = 'pic_proyek' and pr.opd_id = a.opd_id)
        or (a.role = 'vendor' and x.vendor_id = a.vendor_id
            and x.status in ('disetujui', 'berjalan', 'selesai')))
   and (p_status is null or x.status = p_status)
   and (q.kata is null or lower(pr.nomor) = lower(q.kata)
        or greatest(word_similarity(q.kata, pr.judul), word_similarity(q.kata, vn.nama)) >= 0.6)
 order by x.mulai desc, pr.nomor asc, vn.nama asc
 limit least(greatest(coalesce(p_limit, 200), 1), 200);
$$;

