-- ---------------------------------------------------------------------------
-- hitung_vendor_proyek: the readiness engine (section 5). Every vendor offering
-- at least one required category gets a pass or fail, its reasons, and a score.
-- A project with several requirements is judged as a whole: all categories and
-- certificates are required, and the workforce need is the sum of the requirements.
-- ---------------------------------------------------------------------------
create or replace function hitung_vendor_proyek(p_project_id uuid)
returns table (
  vendor_id uuid, nama text, status text, wilayah text,
  lolos boolean, alasan_gugur text[], skor numeric,
  s_pengalaman numeric, s_kinerja numeric, s_waktu numeric,
  s_kapasitas numeric, s_harga numeric, s_wilayah numeric,
  proyek_paralel int, kapasitas_proyek int, sisa_proyek int,
  total_tenaga int, tenaga_terpakai int, sisa_tenaga int, tenaga_dibutuhkan int,
  belum_ada_riwayat boolean, jumlah_pengalaman int, rating numeric, tepat_waktu_persen numeric,
  sertifikat_wajib text[]
)
language sql stable
set search_path = public, pg_temp
as $$
with pr as (
  select p.id, p.mulai, p.selesai, p.anggaran, p.wilayah from projects p where p.id = p_project_id
),
req as (
  select array_agg(distinct r.category_id) as kategori,
         sum(r.tenaga_min)::int as tenaga,
         coalesce((select array_agg(distinct s order by s)
                     from project_requirements r2
                    cross join lateral unnest(r2.sertifikat_wajib) as s
                    where r2.project_id = p_project_id), '{}') as wajib
    from project_requirements r
   where r.project_id = p_project_id
  having count(*) > 0
),
dasar as (
  select v.id, v.nama, v.status, v.wilayah, v.kapasitas_proyek as kap, v.total_tenaga as tot,
         pr.anggaran, pr.wilayah as wilayah_proyek, req.kategori, req.tenaga, req.wajib,
         (select array_agg(c.nama order by c.nama)
            from unnest(req.kategori) as k(id)
            join service_categories c on c.id = k.id
           where not exists (select 1 from vendor_services s
                              where s.vendor_id = v.id and s.category_id = k.id)) as layanan_kurang,
         (select array_agg(w.jenis order by w.jenis)
            from unnest(req.wajib) as w(jenis)
           where not exists (select 1 from vendor_certifications c
                              where c.vendor_id = v.id and c.jenis = w.jenis
                                and c.berlaku_sampai >= pr.selesai)) as sertifikat_kurang,
         exists (select 1 from vendor_unavailability u
                  where u.vendor_id = v.id
                    and daterange(u.mulai, u.selesai, '[]') && daterange(pr.mulai, pr.selesai, '[]')) as tidak_tersedia,
         (select x.status from project_assignments x
           where x.project_id = pr.id and x.vendor_id = v.id
             and x.status in ('diusulkan', 'disetujui', 'berjalan')
           limit 1) as status_di_proyek,
         b.paralel, b.terpakai, h.selesai_total, h.selesai_kategori, n.rata, n.tepat, n.jumlah
    from vendors v
   cross join pr
   cross join req
   cross join lateral (
     select count(*)::int as paralel, coalesce(sum(a.tenaga_dialokasikan), 0)::int as terpakai
       from project_assignments a
      where a.vendor_id = v.id and a.status in ('disetujui', 'berjalan')
        and daterange(a.mulai, a.selesai, '[]') && daterange(pr.mulai, pr.selesai, '[]')
   ) b
   cross join lateral (
     select (select count(*)::int from project_assignments a
              where a.vendor_id = v.id and a.status = 'selesai') as selesai_total,
            (select count(distinct a.project_id)::int from project_assignments a
               join project_requirements r on r.project_id = a.project_id
              where a.vendor_id = v.id and a.status = 'selesai'
                and r.category_id = any (req.kategori)) as selesai_kategori
   ) h
   cross join lateral (
     select avg(r.skor_kualitas) as rata,
            avg(case when r.tepat_waktu then 1 else 0 end) as tepat,
            count(*)::int as jumlah
       from vendor_ratings r where r.vendor_id = v.id
   ) n
   where exists (select 1 from vendor_services s
                  where s.vendor_id = v.id and s.category_id = any (req.kategori))
),
cek as (
  select d.*,
         array_remove(array[
           case when d.status <> 'aktif' then 'Status vendor ' || replace(d.status, '_', ' ') end,
           case when d.layanan_kurang is not null
                then 'Tidak memiliki layanan kategori ' || array_to_string(d.layanan_kurang, ', ') end,
           case when d.sertifikat_kurang is not null
                then 'Sertifikat ' || array_to_string(d.sertifikat_kurang, ', ') || ' tidak berlaku sampai proyek selesai' end,
           case when d.tidak_tersedia then 'Tidak tersedia pada periode proyek' end,
           case when d.paralel >= d.kap
                then 'Kapasitas proyek penuh (' || d.paralel || ' dari ' || d.kap || ')' end,
           case when d.tot - d.terpakai < d.tenaga
                then 'Sisa tenaga ' || greatest(d.tot - d.terpakai, 0) || ', dibutuhkan ' || d.tenaga end,
           case when d.status_di_proyek = 'diusulkan' then 'Sudah diusulkan pada proyek ini'
                when d.status_di_proyek is not null then 'Sudah ditugaskan pada proyek ini' end
         ], null) as alasan,
         (d.selesai_total = 0 and d.jumlah = 0) as tanpa_riwayat
    from dasar d
),
komponen as (
  select c.*,
         round(case when c.tanpa_riwayat then 5   -- neutral: equal to one finished project
                    else 25 * least(c.selesai_kategori, 5) / 5.0 end, 2) as p_pengalaman,
         round(25 * coalesce(c.rata, 3) / 5.0, 2) as p_kinerja,
         round(15 * coalesce(c.tepat, 0.6), 2) as p_waktu,
         round(15 * (1 - c.paralel::numeric / nullif(c.kap, 0)), 2) as p_kapasitas,
         case when c.anggaran is not null and not exists (
                select 1 from unnest(c.kategori) as k(id)
                 where not exists (select 1 from vendor_services s
                                    where s.vendor_id = c.id and s.category_id = k.id
                                      and s.harga_min <= c.anggaran))
              then 10.00 else 0.00 end as p_harga,
         case when lower(trim(c.wilayah)) = lower(trim(c.wilayah_proyek)) then 10.00 else 5.00 end as p_wilayah
    from cek c
)
select k.id, k.nama, k.status, k.wilayah,
       cardinality(k.alasan) = 0,
       k.alasan,
       case when cardinality(k.alasan) = 0
            then k.p_pengalaman + k.p_kinerja + k.p_waktu + k.p_kapasitas + k.p_harga + k.p_wilayah end,
       case when cardinality(k.alasan) = 0 then k.p_pengalaman end,
       case when cardinality(k.alasan) = 0 then k.p_kinerja end,
       case when cardinality(k.alasan) = 0 then k.p_waktu end,
       case when cardinality(k.alasan) = 0 then k.p_kapasitas end,
       case when cardinality(k.alasan) = 0 then k.p_harga end,
       case when cardinality(k.alasan) = 0 then k.p_wilayah end,
       k.paralel, k.kap, greatest(k.kap - k.paralel, 0),
       k.tot, k.terpakai, greatest(k.tot - k.terpakai, 0), k.tenaga,
       k.tanpa_riwayat, k.selesai_kategori,
       round(k.rata, 2), round(100 * k.tepat, 0), k.wajib
  from komponen k
 order by 5 desc, 7 desc nulls last, 2 asc;
$$;

-- ---------------------------------------------------------------------------
-- cari_vendor_ready: vendors that pass every mandatory check, highest score first.
-- ---------------------------------------------------------------------------
create or replace function cari_vendor_ready(p_project_id uuid)
returns table (
  vendor_id uuid, nama text, skor numeric,
  s_pengalaman numeric, s_kinerja numeric, s_waktu numeric,
  s_kapasitas numeric, s_harga numeric, s_wilayah numeric,
  proyek_paralel int, sisa_proyek int, sisa_tenaga int
)
language sql stable
set search_path = public, pg_temp
as $$
  select h.vendor_id, h.nama, h.skor,
         h.s_pengalaman, h.s_kinerja, h.s_waktu, h.s_kapasitas, h.s_harga, h.s_wilayah,
         h.proyek_paralel, h.sisa_proyek, h.sisa_tenaga
    from hitung_vendor_proyek(p_project_id) h
   where h.lolos
   order by h.skor desc, h.nama asc;
$$;

-- ---------------------------------------------------------------------------
-- rekomendasi_vendor_proyek: the ranked result for one project, limited by role.
-- Returns null when the actor may not see the project. Vendors never get it.
-- ---------------------------------------------------------------------------
create or replace function rekomendasi_vendor_proyek(p_actor uuid, p_project_id uuid)
returns jsonb
language sql stable
set search_path = public, pg_temp
as $$
with izin as (
  select pr.id, pr.nomor, pr.judul, pr.status, pr.mulai, pr.selesai, pr.anggaran, pr.wilayah, o.nama as opd
    from projects pr
    join opd o on o.id = pr.opd_id
    join profiles a on a.id = p_actor
   where pr.id = p_project_id
     and (a.role in ('admin_pengadaan', 'kepala_dinas')
          or (a.role = 'pic_proyek' and pr.opd_id = a.opd_id))
),
hasil as (
  select h.*, row_number() over (partition by h.lolos order by h.skor desc nulls last, h.nama asc)::int as peringkat
    from izin
   cross join lateral hitung_vendor_proyek(izin.id) h
),
alasan as (
  select regexp_replace(a, ' \(.*\)$', '') as teks, count(*)::int as jumlah
    from hasil h
   cross join lateral unnest(h.alasan_gugur) as a
   where not h.lolos
   group by 1
   order by 2 desc, 1 asc
   limit 3
)
select jsonb_build_object(
  'proyek', to_jsonb(i),
  'kebutuhan', coalesce((
    select jsonb_agg(jsonb_build_object(
             'kategori', c.nama, 'tenaga_min', r.tenaga_min, 'sertifikat_wajib', to_jsonb(r.sertifikat_wajib))
             order by c.nama)
      from project_requirements r join service_categories c on c.id = r.category_id
     where r.project_id = i.id), '[]'::jsonb),
  'jumlah_ready', (select count(*)::int from hasil where lolos),
  'jumlah_gugur', (select count(*)::int from hasil where not lolos),
  'ready', coalesce((select jsonb_agg(to_jsonb(h) order by h.peringkat) from hasil h where h.lolos), '[]'::jsonb),
  'gugur', coalesce((select jsonb_agg(jsonb_build_object(
             'vendor_id', h.vendor_id, 'nama', h.nama, 'status', h.status, 'alasan_gugur', to_jsonb(h.alasan_gugur))
             order by h.nama) from hasil h where not h.lolos), '[]'::jsonb),
  'alasan_terbanyak', coalesce((select jsonb_agg(jsonb_build_object('alasan', a.teks, 'jumlah', a.jumlah)
             order by a.jumlah desc, a.teks) from alasan a), '[]'::jsonb)
)
from izin i;
$$;

-- ---------------------------------------------------------------------------
-- cek_ketersediaan_vendor: can one vendor take work in a given period?
-- A vendor account may only check itself.
-- ---------------------------------------------------------------------------
create or replace function cek_ketersediaan_vendor(
  p_actor uuid, p_vendor_id uuid, p_mulai date, p_selesai date, p_tenaga int default 0
)
returns jsonb
language plpgsql stable
set search_path = public, pg_temp
as $$
declare
  actor profiles%rowtype;
  v vendors%rowtype;
  v_paralel int;
  v_terpakai int;
  v_bentrok jsonb;
  v_sertifikat text[];
  v_tenaga int := greatest(coalesce(p_tenaga, 0), 0);
  v_alasan text[] := '{}';
begin
  select * into actor from profiles where id = p_actor;
  if not found or (actor.role = 'vendor' and p_vendor_id is distinct from actor.vendor_id) then
    raise exception 'akses_ditolak';
  end if;
  if p_mulai is null or p_selesai is null or p_selesai < p_mulai then
    raise exception 'periode_tidak_valid';
  end if;

  select * into v from vendors where id = p_vendor_id;
  if not found then
    return null;
  end if;

  select count(*)::int, coalesce(sum(a.tenaga_dialokasikan), 0)::int
    into v_paralel, v_terpakai
    from project_assignments a
   where a.vendor_id = v.id and a.status in ('disetujui', 'berjalan')
     and daterange(a.mulai, a.selesai, '[]') && daterange(p_mulai, p_selesai, '[]');

  select jsonb_agg(jsonb_build_object('mulai', u.mulai, 'selesai', u.selesai, 'alasan', u.alasan) order by u.mulai)
    into v_bentrok
    from vendor_unavailability u
   where u.vendor_id = v.id
     and daterange(u.mulai, u.selesai, '[]') && daterange(p_mulai, p_selesai, '[]');

  select array_agg(distinct c.jenis order by c.jenis)
    into v_sertifikat
    from vendor_certifications c
   where c.vendor_id = v.id and c.berlaku_sampai < p_selesai;

  if v.status <> 'aktif' then
    v_alasan := v_alasan || ('Status vendor ' || replace(v.status, '_', ' '));
  end if;
  if v_bentrok is not null then
    v_alasan := v_alasan || 'Tidak tersedia pada periode ini'::text;
  end if;
  if v_paralel >= v.kapasitas_proyek then
    v_alasan := v_alasan || ('Kapasitas proyek penuh (' || v_paralel || ' dari ' || v.kapasitas_proyek || ')');
  end if;
  if v.total_tenaga - v_terpakai < v_tenaga then
    v_alasan := v_alasan || ('Sisa tenaga ' || greatest(v.total_tenaga - v_terpakai, 0) || ', dibutuhkan ' || v_tenaga);
  end if;

  return jsonb_build_object(
    'vendor_id', v.id, 'nama', v.nama, 'status', v.status,
    'mulai', p_mulai, 'selesai', p_selesai, 'tenaga_diminta', v_tenaga,
    'bisa', cardinality(v_alasan) = 0, 'alasan', to_jsonb(v_alasan),
    'proyek_paralel', v_paralel, 'kapasitas_proyek', v.kapasitas_proyek,
    'sisa_proyek', greatest(v.kapasitas_proyek - v_paralel, 0),
    'total_tenaga', v.total_tenaga, 'tenaga_terpakai', v_terpakai,
    'sisa_tenaga', greatest(v.total_tenaga - v_terpakai, 0),
    'periode_bentrok', coalesce(v_bentrok, '[]'::jsonb),
    'sertifikat_habis_sebelum_selesai', to_jsonb(coalesce(v_sertifikat, '{}'))
  );
end $$;

