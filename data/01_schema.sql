create table if not exists vendors (
  id                uuid primary key default gen_random_uuid(),
  nama              text not null,
  npwp              text unique,
  alamat            text,
  wilayah           text,
  kontak            text,
  tipe              text not null check (tipe in ('barang', 'jasa', 'barang_jasa')),
  status            text not null default 'draft'
                    check (status in ('draft', 'verifikasi', 'aktif', 'ditolak', 'daftar_hitam', 'diarsipkan')),
  kapasitas_proyek  int not null default 1 check (kapasitas_proyek >= 0),
  total_tenaga      int not null default 0 check (total_tenaga >= 0),
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

alter table vendors drop constraint if exists vendors_status_check;
alter table vendors add constraint vendors_status_check
  check (status in ('draft', 'verifikasi', 'aktif', 'ditolak', 'daftar_hitam', 'diarsipkan'));

create table if not exists profiles (
  id         uuid primary key references auth.users (id) on delete cascade,
  nama       text not null,
  role       text not null
             check (role in ('admin_pengadaan', 'pic_proyek', 'kepala_dinas', 'vendor')),
  opd_id     int references opd (id) on delete set null,
  vendor_id  uuid references vendors (id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists vendor_services (
  id            uuid primary key default gen_random_uuid(),
  vendor_id     uuid not null references vendors (id) on delete cascade,
  category_id   int not null references service_categories (id),
  nama_layanan  text not null,
  tipe          text not null check (tipe in ('barang', 'jasa')),
  deskripsi     text,
  harga_min     numeric(16, 2) check (harga_min >= 0),
  harga_maks    numeric(16, 2),
  satuan        text,
  check (harga_maks is null or harga_min is null or harga_maks >= harga_min)
);

create table if not exists vendor_certifications (
  id              uuid primary key default gen_random_uuid(),
  vendor_id       uuid not null references vendors (id) on delete cascade,
  jenis           text not null,
  nomor           text,
  berlaku_sampai  date not null
);

create table if not exists vendor_unavailability (
  id         uuid primary key default gen_random_uuid(),
  vendor_id  uuid not null references vendors (id) on delete cascade,
  mulai      date not null,
  selesai    date not null,
  alasan     text,
  check (selesai >= mulai)
);

create table if not exists vendor_documents (
  id            uuid primary key default gen_random_uuid(),
  vendor_id     uuid not null references vendors (id) on delete cascade,
  jenis         text not null,
  file_path     text not null,
  hasil_cek_ai  jsonb,
  status_cek    text not null default 'belum'
                check (status_cek in ('belum', 'lengkap', 'tidak_cocok', 'perlu_diperiksa_manual')),
  created_at    timestamptz not null default now()
);

